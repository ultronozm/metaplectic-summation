#!/usr/bin/env python3
"""Generate Solution.lean from Challenge.lean.

The Solution keeps every definition and theorem statement of the Challenge
verbatim (Comparator requires identical statements) and replaces each `sorry`
by the proof stored in scripts/solution-proofs.lean-fragment under the same theorem name.
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
challenge = (root / 'Challenge.lean').read_text()
proofs_src = (root / 'scripts' / 'solution-proofs.lean-fragment').read_text()

# Proof bodies: blocks "-- proof: NAME" up to the next marker.
bridge, _, rest = proofs_src.partition('-- proof:')
proofs = {}
for block in ('-- proof:' + rest).split('-- proof:')[1:]:
    name, _, body = block.partition('\n')
    proofs[name.strip()] = body.rstrip() + '\n'

header = ("import Mathlib\nimport MetaplecticSummation\n\n"
          "/-! Generated by scripts/make-solution.py from Challenge.lean and scripts/solution-proofs.lean-fragment.\n"
          "Do not edit by hand. -/\n\n")
body = challenge
body = re.sub(r'^import Mathlib\n', '', body)
# Insert the bridge before the first theorem section.
marker = '/-! ## Existence of the characterized objects -/'
before, _, after = body.partition(marker)
body = before + bridge.strip() + '\n\n' + marker + after

def repl(m):
    name = m.group(1)
    if name not in proofs:
        sys.exit(f'missing proof for {name}')
    return m.group(0).replace('by\n  sorry\n', proofs[name] if proofs[name].startswith(' ') else proofs[name])

pattern = re.compile(r'theorem (\w+)(?:(?!\ntheorem ).)*?:= by\n  sorry\n', re.S)
out, count = pattern.subn(lambda m: m.group(0)[:-len('by\n  sorry\n')] + proofs[m.group(1)], body)
missing = [n for n in re.findall(r'theorem (\w+)', challenge) if n not in proofs]
if missing:
    sys.exit(f'missing proofs: {missing}')
(root / 'Solution.lean').write_text(header + out)
print(f'wrote Solution.lean with {count} proofs')
